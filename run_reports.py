"""Run the SQLite example, verify expected results, and export Markdown tables."""
from pathlib import Path
import sqlite3

ROOT = Path(__file__).resolve().parent


def read_queries(filename):
    statements = []
    pending = ''
    for line in (ROOT / filename).read_text(encoding='utf-8').splitlines(True):
        pending += line
        if sqlite3.complete_statement(pending):
            statements.append(pending)
            pending = ''
    if pending.strip():
        raise ValueError(f'Incomplete SQL in {filename}')
    return statements


def markdown_table(columns, rows):
    lines = ['| ' + ' | '.join(columns) + ' |',
             '| ' + ' | '.join(['---'] * len(columns)) + ' |']
    for row in rows:
        values = ['N/A' if value is None else str(value) for value in row]
        lines.append('| ' + ' | '.join(values) + ' |')
    return '\n'.join(lines)


def main():
    # A fresh in-memory database makes repeated runs reproducible.
    connection = sqlite3.connect(':memory:')
    connection.executescript((ROOT / 'schema_and_data.sql').read_text(encoding='utf-8'))
    reports = []
    output = ['# Verified results', '',
              'Generated by `python run_reports.py` from the synthetic dataset.', '']
    titles = ['Monthly report', 'Language report', 'Monthly comparison', 'Data quality']
    queries = read_queries('reports.sql') + read_queries('quality_checks.sql')
    for title, query in zip(titles, queries):
        cursor = connection.execute(query)
        rows = cursor.fetchall()
        reports.append(rows)
        columns = [column[0] for column in cursor.description]
        output.extend(['## ' + title, '', markdown_table(columns, rows), ''])

    expected_monthly = [
        ('2026-08-01', 8, 5, 3, 37.5),
        ('2026-09-01', 8, 6, 2, 25.0),
        ('2026-10-01', 8, 7, 1, 12.5),
        ('2026-11-01', 0, 0, 0, None),
    ]
    assert reports[0] == expected_monthly, 'Monthly totals or rates are incorrect'
    assert reports[1] == [
        ('Arabic', 0, 0, None, 0, None),
        ('English', 9, 1, 11.11, 8, 29.13),
        ('French', 6, 3, 50.0, 6, 56.33),
        ('Spanish', 9, 2, 22.22, 9, 35.11),
    ], 'Language joins or missing-value treatment are incorrect'
    assert reports[2] == [
        ('2026-08-01', 37.5, None, None),
        ('2026-09-01', 25.0, 37.5, -12.5),
        ('2026-10-01', 12.5, 25.0, -12.5),
        ('2026-11-01', None, 12.5, None),
    ], 'Window comparison is incorrect'
    assert reports[3] == [(24, 24, 0, 1, 0, 0, 0)], 'Data quality differs from fixture'
    assert sum(row[1] for row in reports[0]) == sum(row[1] for row in reports[1]) == 24
    output.extend(['All expected-result and reconciliation checks passed.', ''])
    (ROOT / 'RESULTS.md').write_text('\n'.join(output), encoding='utf-8')
    connection.close()
    print('PASS: three reports, data quality, empty groups, missing waits, and reconciliation.')
    print('Saved RESULTS.md')


if __name__ == '__main__':
    main()
